"""死の扱いをシナリオが選べるようにする設定。

## なぜ engine 固定ではいけないか

無人島のような世界では「倒れた仲間に駆けつけて助け起こす」が成立してほしい。
秘匿役職の世界では、殺しは静かに起き、死は確定し、死体だけが残ってほしい。
**同じ engine に両方が要る。**

既定は従来の挙動 (蘇生できる / 全員に気配が届く / 被害者は加害者を知る) に
してある。宣言しないシナリオの挙動は変わらない。

## 過去の判断との関係

- ``design_decisions`` #848「倒れているだけの相手は蘇生できるので生存として
  数える」→ **蘇生のある世界での判断**として残る。``grace_ticks=0`` の世界では
  倒れた時点で退場が確定する
- #873「会議は救命猶予より必ず短い」→ 同じく蘇生のある世界での判断。救命の
  余地が無い世界では意味を持たない

どちらも当時は正しく、秘匿役職を想定していなかっただけ。捨てるのではなく
条件付きにする。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class DeathSemantics:
    """その世界で、死がどう扱われるか。"""

    #: 倒れてから退場が確定するまでの猶予 tick。``None`` なら engine の既定。
    #:
    #: ``0`` にすると倒れた時点で確定する。**蘇生が成立しなくなる**ので、
    #: 秘匿役職のように「殺したら死ぬ」世界はこれを選ぶ。
    grace_ticks: int | None = None

    #: 倒れたことを、その場に居ない者にも伝えるか。
    #:
    #: ``False`` にすると「遠くで誰かが倒れた気配がした」が出なくなる。
    #: **隠密殺人はこれが False でないと成立しない。** 倒れた瞬間に全員が
    #: 知るなら、死体を見つける意味も通報する意味も無い。
    announce_globally: bool = True

    #: 倒された本人が、加害者の名前を知るか。
    #:
    #: engine の既定は「本人視点では当然分かる」。ただしシナリオが匿名の
    #: 通知文 (``target_observation_message``) を宣言している場合、直後に
    #: 加害者名が届くと**匿名にした意味が消える**。実 run で衝突した。
    victim_learns_killer: bool = True
